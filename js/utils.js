function loadSavedPetProfile() {
  try {
    const saved = localStorage.getItem('furever_active_pet') || sessionStorage.getItem('fureverPet');
    if (saved) return JSON.parse(saved);
  } catch (e) {
    console.warn('Failed to parse saved pet profile', e);
  }
  return null;
}

function savePetProfileToStorage(pet) {
  try {
    localStorage.setItem('furever_active_pet', JSON.stringify(pet));
    sessionStorage.setItem('fureverPet', JSON.stringify(pet));
  } catch (e) {
    console.warn('Failed to save pet profile', e);
  }
}
